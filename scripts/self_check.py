# 5. Never ship a private key from the project tree.
for path in ROOT.rglob("*"):
    if not path.is_file():
        continue
    name = path.name.lower()
    if name in {"private_key", "id_rsa"} or name.endswith((".pem", ".key")):
        fail(f"private key-like file found: {path.relative_to(ROOT)}")
    if path.suffix.lower() in {".py", ".txt", ".md", ".json", ".iss", ".bat", ".yml", ".yaml"}:
        try:
            content = path.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        if re.search(
            r"-----BEGIN PRIVATE KEY-----\s+[A-Za-z0-9+/=\r\n]{80,}-----END PRIVATE KEY-----",
            content,
            re.MULTILINE,
        ):
            fail(f"private key material found: {path.relative_to(ROOT)}")



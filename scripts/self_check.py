# 1b. UI classes must not call private self-methods that do not exist.
# Python compiles such code successfully and only fails when the affected page is opened.
for path in sorted((SRC / "ui").rglob("*.py")):
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for cls in (node for node in ast.walk(tree) if isinstance(node, ast.ClassDef)):
        methods = {
            node.name
            for node in cls.body
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        }
        assigned = set()
        calls = set()
        for node in ast.walk(cls):
            if isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                for target in targets:
                    if (
                        isinstance(target, ast.Attribute)
                        and isinstance(target.value, ast.Name)
                        and target.value.id == "self"
                    ):
                        assigned.add(target.attr)
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id == "self"
                and node.func.attr.startswith("_")
            ):
                calls.add(node.func.attr)
        missing = sorted(calls - methods - assigned)
        if missing:
            fail(
                f"{path.relative_to(ROOT)}:{cls.name} calls missing private method(s): "
                + ", ".join(missing)
            )

